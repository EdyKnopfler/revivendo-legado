  FOREIGN KEY (ID_COMPRA) REFERENCES COMPRAS (ID_COMPRA) ON UPDATE CASCADE ON DELETE CASCADE;
ALTER TABLE ITENS_COMPRA ADD CONSTRAINT FK_ITENS_COMPRA_PRODUTOS
  FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTOS (ID_PRODUTO);
ALTER TABLE ITENS_PEDIDO ADD CONSTRAINT FK_ITENS_PEDIDO_PEDIDOS
  FOREIGN KEY (ID_PEDIDO) REFERENCES PEDIDOS (ID_PEDIDO) ON UPDATE CASCADE ON DELETE CASCADE;
ALTER TABLE ITENS_PEDIDO ADD CONSTRAINT FK_ITENS_PEDIDO_PRODUTOS
  FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTOS (ID_PRODUTO);
